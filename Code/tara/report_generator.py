import datetime
from tara.traceability import TraceabilityMatrix


def generate_tara_report(session_data: dict, execution_mode: str = "DEMO FALLBACK") -> str:
    """
    Generate a structured TARA Engineering Report from the current session.
    - Derives valid threat IDs once and filters risks/mitigations by those IDs.
    - Renders rejected/incomplete candidates in a separate section.
    - Uses the same filtered records for the traceability matrix and review counts.
    - Never populates an empty session with invented findings.
    """
    now_str = datetime.datetime.now().strftime("%Y-%m-%d %H:%M:%S")

    assets = session_data.get('assets') or []
    surfaces = session_data.get('attack_surfaces') or []
    raw_threats = session_data.get('threats') or []
    requirements = session_data.get('requirements') or []

    # ── 1. Filter threats once ────────────────────────────────────────────
    valid_threats = [t for t in raw_threats if getattr(t, 'is_valid', lambda: True)()]
    excluded_threats = [
        t for t in raw_threats
        if not getattr(t, 'is_valid', lambda: True)()
        or getattr(t, 'review_status', '') == 'rejected'
    ]
    valid_threat_ids = {t.threat_id for t in valid_threats}

    # ── 2. Filter risks and mitigations to only those linked to valid threats ─
    raw_risks = session_data.get('risks') or []
    valid_risks = [r for r in raw_risks if r.threat_id in valid_threat_ids]
    orphaned_risks = [r for r in raw_risks if r.threat_id not in valid_threat_ids]

    raw_mitigations = session_data.get('mitigations') or []
    valid_mits = [
        m for m in raw_mitigations
        if m.threat_id in valid_threat_ids and getattr(m, 'is_valid', lambda: True)()
    ]
    orphaned_mits = [
        m for m in raw_mitigations
        if m.threat_id not in valid_threat_ids or not getattr(m, 'is_valid', lambda: True)()
    ]

    has_findings = any([assets, surfaces, valid_threats, valid_risks, valid_mits])

    if not has_findings:
        return (
            f"# Automotive Cybersecurity TARA Engineering Report\n"
            f"**Generated:** {now_str}  \n"
            f"**Execution Mode:** {execution_mode}  \n"
            f"**Session Status:** Empty Session (No Findings) — No Valid Findings  \n\n"
            f"## Notice: No Analysis Findings in Current Session\n"
            f"No valid analysis findings were found. The report cannot be populated with invented findings.\n\n"
            f"Please execute the upstream TARA workflow stages before generating a report.\n\n"
            f"---\n"
            f"> **Advisory Disclaimer:** Informed by ISO/SAE 21434 and UNECE R155 concepts. "
            f"No compliance is claimed.\n"
        )

    lines = []
    lines.append("# Automotive Cybersecurity TARA Engineering Report")
    lines.append(f"**Generated:** {now_str}  ")
    lines.append(f"**Execution Mode:** {execution_mode}  ")
    lines.append("**Framework Alignment:** Informed by ISO/SAE 21434:2021 & UNECE R155 concepts  ")
    lines.append("**Status:** Engineering Candidate Findings — Qualified Human Review Required  \n")

    if "DEMO" in execution_mode.upper():
        lines.append("> [!WARNING]")
        lines.append("> **DEMO MODE — PREDEFINED DATA ACTIVE:** Findings below were synthesized via offline deterministic demonstration data (fallback mode). They were NOT generated by Google Gemini live API and do not represent document-extracted findings. Qualified human review is required.\n")

    lines.append("---\n")

    # 1. Assets
    lines.append("## 1. Discovered Assets & Security Properties\n")
    if assets:
        lines.append("| Asset Name | Type | Related Interface | Security Properties | Review Status |")
        lines.append("|---|---|---|---|---|")
        for a in assets:
            props = ", ".join(a.security_properties) if isinstance(a.security_properties, list) else str(a.security_properties)
            lines.append(f"| {a.name} | {a.asset_type} | {a.related_interface or 'N/A'} | {props} | {a.review_status} |")
        lines.append("")
    else:
        lines.append("*No asset analysis findings in current session.*\n")

    # 2. Attack Surfaces
    lines.append("## 2. Attack Surface Analysis\n")
    if surfaces:
        lines.append("| Interface | Connected Component | Exposure | Security Concern | Review Status |")
        lines.append("|---|---|---|---|---|")
        for s in surfaces:
            lines.append(f"| {s.interface} | {s.connected_component} | {s.exposure} | {s.security_concern} | {s.review_status} |")
        lines.append("")
    else:
        lines.append("*No attack surface findings in current session.*\n")

    # 3. STRIDE Threats & Evidence Grounding
    lines.append("## 3. STRIDE Threat Scenarios & Evidence Grounding\n")
    if valid_threats:
        for t in valid_threats:
            lines.append(f"### {t.threat_id}: {t.threat} (Target: {t.asset})")
            lines.append(f"- **Attack Surface:** {t.attack_surface or 'Not specified'}")
            lines.append(f"- **Description:** {t.threat_description}")
            lines.append(f"- **Potential Impact:** {t.potential_impact}")
            lines.append(f"- **Preconditions:** {t.preconditions or 'Not documented'}")
            lines.append(f"- **Confidence:** {t.confidence} | **Human Review Status:** {t.review_status}")
            completeness = getattr(t, 'completeness_notes', lambda: [])() if hasattr(t, 'completeness_notes') else []
            if completeness:
                lines.append(f"- **⚠ Completeness Warnings:** {'; '.join(completeness)}")
            if t.evidence:
                lines.append(f"- **Supporting Knowledge-Base Evidence ({len(t.evidence)} citations):**")
                for idx, c in enumerate(t.evidence, 1):
                    sec_info = f", Section: {c.section}" if c.section else ""
                    lines.append(f"  - [{idx}] *{c.document_name}*{sec_info} (Relevance: {c.relevance_score:.2f})")
                    snippet = c.chunk_text[:200].replace("\n", " ").strip()
                    lines.append(f"    > \"{snippet}...\"")
            else:
                lines.append("- **Supporting Evidence:** *None — Unverified Hypothesis. Direct validation required.*")
            lines.append("")
    else:
        lines.append("*No valid threat scenarios in current session.*\n")

    # 4. Risk Assessment (linked to valid threats only)
    lines.append("## 4. Deterministic Risk Assessment\n")
    if valid_risks:
        lines.append("| Threat | Target Asset | Impact Score | Feasibility | Risk Score | Risk Level | Review Status |")
        lines.append("|---|---|---|---|---|---|---|")
        for r in valid_risks:
            lines.append(f"| {r.threat} | {r.asset} | {r.impact_score} | {r.attack_feasibility} ({r.feasibility_score}) | {r.risk_score} | {r.risk_level} | {r.review_status} |")
        lines.append("")
        lines.append("### Risk Scoring Rationales")
        for r in valid_risks:
            lines.append(f"- **{r.threat_id} ({r.threat}):** {r.scoring_rationale}")
        lines.append("")
        if orphaned_risks:
            lines.append(f"*Note: {len(orphaned_risks)} risk record(s) were excluded because their threat_id references excluded or invalid threats.*\n")
    else:
        lines.append("*No risk assessment performed in current session.*\n")

    # 5. Defensive Mitigations (linked to valid threats only)
    lines.append("## 5. Threat-Specific Defensive Mitigation Recommendations\n")
    if valid_mits:
        for m in valid_mits:
            lines.append(f"### {m.mitigation_id}: {m.recommended_control}")
            lines.append(f"- **Target Threat:** {m.threat_id} ({m.threat})")
            lines.append(f"- **Control Category:** `{m.control_category}`")
            lines.append(f"- **Technical Recommendation:** {m.description}")
            lines.append(f"- **Confidence:** {m.confidence} | **Review Status:** {m.review_status}")
            if m.evidence:
                docs = ", ".join(sorted(set(c.document_name for c in m.evidence)))
                lines.append(f"- **Referenced Mitigation Evidence:** {docs}")
            else:
                lines.append("- **Referenced Mitigation Evidence:** *No direct citations (Hypothesis)*")
            lines.append("")
        if orphaned_mits:
            lines.append(f"*Note: {len(orphaned_mits)} mitigation record(s) were excluded because their threat_id references excluded or invalid threats.*\n")
    else:
        lines.append("*No mitigation recommendations in current session.*\n")

    # 6. Traceability Matrix (same filtered sets)
    lines.append("## 6. End-to-End Traceability Matrix\n")
    if valid_threats:
        matrix = TraceabilityMatrix()
        matrix.build(assets, valid_threats, valid_mits, requirements, valid_risks)
        trace_rows = matrix.to_full_traceability_table()
        lines.append("| Target Asset | Attack Surface | Threat | Impact | Feasibility | Risk Score | Supporting Evidence | Mitigation Control | Review Status |")
        lines.append("|---|---|---|---|---|---|---|---|---|")
        for tr in trace_rows:
            lines.append(f"| {tr['Asset']} | {tr['Attack Surface']} | {tr['Threat']} | {tr['Impact']} | {tr['Feasibility']} | {tr['Risk Score']} | {tr['Supporting Evidence']} | {tr['Mitigation']} | {tr['Review Status']} |")
        lines.append("")
    else:
        lines.append("*Traceability matrix requires identified valid threats.*\n")

    # 7. Excluded / Rejected Candidates
    if excluded_threats or orphaned_risks or orphaned_mits:
        lines.append("## 7. Excluded & Rejected Candidates\n")
        lines.append("> The following candidates were excluded from the main findings due to structural invalidity or explicit rejection.\n")
        if excluded_threats:
            lines.append("### Excluded Threats")
            lines.append("| Threat ID | Name | Asset | Reason |")
            lines.append("|---|---|---|---|")
            for t in excluded_threats:
                reason = getattr(t, 'rejection_reason', '') or getattr(t, 'validation_error', lambda: 'N/A')()
                lines.append(f"| {t.threat_id} | {t.threat or '[empty]'} | {t.asset or '[empty]'} | {reason} |")
            lines.append("")
        if orphaned_risks:
            lines.append("### Orphaned Risk Records (no valid threat reference)")
            for r in orphaned_risks:
                lines.append(f"- {r.risk_id}: threat_id='{r.threat_id}' — excluded because threat is invalid or rejected")
            lines.append("")
        if orphaned_mits:
            lines.append("### Orphaned Mitigation Records (no valid threat reference)")
            for m in orphaned_mits:
                lines.append(f"- {m.mitigation_id}: threat_id='{m.threat_id}' — excluded because threat is invalid or rejected")
            lines.append("")

    # 8. Human Review Summary (same filtered records)
    section_num = 8 if (excluded_threats or orphaned_risks or orphaned_mits) else 7
    all_items = assets + surfaces + valid_threats + valid_risks + valid_mits + requirements
    if all_items:
        lines.append(f"## {section_num}. Human Review & Engineering Sign-Off Status\n")
        status_counts: dict = {}
        for item in all_items:
            st_val = getattr(item, 'review_status', 'needs_review')
            status_counts[st_val] = status_counts.get(st_val, 0) + 1
        lines.append("| Review Status | Item Count | Description |")
        lines.append("|---|---|---|")
        lines.append(f"| Accepted | {status_counts.get('accepted', 0)} | Reviewed and accepted |")
        lines.append(f"| Needs Review | {status_counts.get('needs_review', 0)} | Awaiting engineering review |")
        lines.append(f"| Edited | {status_counts.get('edited', 0)} | Modified during review |")
        lines.append(f"| Rejected | {status_counts.get('rejected', 0)} | Rejected by engineer |")
        lines.append("")

    lines.append("---\n")
    lines.append("> **Advisory Disclaimer:** AI-assisted engineering prototype informed by ISO/SAE 21434:2021 & UNECE R155. All findings require formal review by qualified automotive cybersecurity engineers. No certification or compliance is claimed.\n")

    return "\n".join(lines)

    
    if not has_findings:
        return (
            f"# Automotive Cybersecurity TARA Engineering Report\n"
            f"**Generated:** {now_str}  \n"
            f"**Execution Mode:** {execution_mode}  \n"
            f"**Session Status:** Empty Session (No Findings)  \n\n"
            f"## Notice: No Analysis Findings in Current Session\n"
            f"No analysis findings were found in the current session. "
            f"The report cannot be populated with invented findings.\n\n"
            f"Please execute the upstream TARA workflow stages before generating a report:\n"
            f"1. **Asset Analysis:** Identify ECUs, buses, and security properties.\n"
            f"2. **Attack Surface Analysis:** Map exposed communication boundaries.\n"
            f"3. **Threat Scenario Generation:** Synthesize grounded STRIDE threat scenarios.\n"
            f"4. **Deterministic Risk Assessment:** Compute qualitative impacts and deterministic risk scores.\n"
            f"5. **Defensive Mitigation Recommendations:** Recommend threat-specific defensive controls.\n\n"
            f"---\n"
            f"> **Advisory Disclaimer:** This prototype is informed by ISO/SAE 21434 and UNECE R155 concepts. "
            f"All findings and ratings require qualified human engineering review and approval. "
            f"No ISO/SAE 21434 certification or automatic compliance is claimed.\n"
        )
    
    lines = []
    lines.append("# Automotive Cybersecurity TARA Engineering Report")
    lines.append(f"**Generated:** {now_str}  ")
    lines.append(f"**Execution Mode:** {execution_mode}  ")
    lines.append("**Framework Alignment:** Informed by ISO/SAE 21434:2021 & UNECE R155 concepts  ")
    lines.append("**Status:** Engineering Candidate Findings — Qualified Human Review Required  \n")
    lines.append("---\n")
    
    # 1. Assets
    lines.append("## 1. Discovered Assets & Security Properties\n")
    if assets:
        lines.append("| Asset Name | Type | Related Interface | Security Properties | Review Status |")
        lines.append("|---|---|---|---|---|")
        for a in assets:
            props = ", ".join(a.security_properties) if isinstance(a.security_properties, list) else str(a.security_properties)
            lines.append(f"| {a.name} | {a.asset_type} | {a.related_interface or 'N/A'} | {props} | {a.review_status} |")
        lines.append("")
    else:
        lines.append("*No asset analysis findings available in current session.*\n")
        
    # 2. Attack Surfaces
    lines.append("## 2. Attack Surface Analysis\n")
    if surfaces:
        lines.append("| Interface | Connected Component | Exposure | Security Concern | Review Status |")
        lines.append("|---|---|---|---|---|")
        for s in surfaces:
            lines.append(f"| {s.interface} | {s.connected_component} | {s.exposure} | {s.security_concern} | {s.review_status} |")
        lines.append("")
    else:
        lines.append("*No attack surface analysis findings available in current session.*\n")
        
    # 3. STRIDE Threats & Evidence Grounding
    lines.append("## 3. STRIDE Threat Scenarios & Evidence Grounding\n")
    if threats:
        for t in threats:
            lines.append(f"### {t.threat_id}: {t.threat} (Target: {t.asset})")
            lines.append(f"- **Attack Surface:** {t.attack_surface}")
            lines.append(f"- **Description:** {t.threat_description}")
            lines.append(f"- **Potential Impact:** {t.potential_impact}")
            lines.append(f"- **Preconditions:** {t.preconditions}")
            lines.append(f"- **Confidence:** {t.confidence} | **Human Review Status:** {t.review_status}")
            
            if t.evidence:
                lines.append(f"- **Supporting Knowledge-Base Evidence ({len(t.evidence)} citations):**")
                for i, c in enumerate(t.evidence, 1):
                    sec_info = f", Section: {c.section}" if c.section else ""
                    lines.append(f"  - [{i}] *{c.document_name}*{sec_info} (Relevance: {c.relevance_score:.2f})")
                    snippet = c.chunk_text[:200].replace("\n", " ").strip()
                    lines.append(f"    > \"{snippet}...\"")
            else:
                lines.append("- **Supporting Evidence:** *None — Marked as Unverified Hypothesis Scenario. Direct knowledge-base validation required.*")
            lines.append("")
    else:
        lines.append("*No threat scenarios generated in current session.*\n")
        
    # 4. Risk Assessment
    lines.append("## 4. Deterministic Risk Assessment\n")
    if risks:
        lines.append("| Threat | Target Asset | Impact Score | Feasibility | Risk Score | Risk Level | Review Status |")
        lines.append("|---|---|---|---|---|---|---|")
        for r in risks:
            lines.append(f"| {r.threat} | {r.asset} | {r.impact_score} | {r.attack_feasibility} ({r.feasibility_score}) | {r.risk_score} | {r.risk_level} | {r.review_status} |")
        lines.append("")
        
        lines.append("### Risk Scoring Rationales")
        for r in risks:
            lines.append(f"- **{r.threat_id} ({r.threat}):** {r.scoring_rationale}")
        lines.append("")
    else:
        lines.append("*No risk assessment performed in current session.*\n")
        
    # 5. Defensive Mitigations
    lines.append("## 5. Threat-Specific Defensive Mitigation Recommendations\n")
    if mitigations:
        for m in mitigations:
            lines.append(f"### {m.mitigation_id}: {m.recommended_control}")
            lines.append(f"- **Target Threat:** {m.threat_id} ({m.threat})")
            lines.append(f"- **Control Category:** `{m.control_category}`")
            lines.append(f"- **Technical Recommendation:** {m.description}")
            lines.append(f"- **Confidence:** {m.confidence} | **Review Status:** {m.review_status}")
            if m.evidence:
                docs = ", ".join(sorted(list(set(c.document_name for c in m.evidence))))
                lines.append(f"- **Referenced Mitigation Evidence:** {docs}")
            else:
                lines.append("- **Referenced Mitigation Evidence:** *No direct citations (Hypothesis)*")
            lines.append("")
    else:
        lines.append("*No mitigation recommendations available in current session.*\n")
        
    # 6. Traceability Matrix
    lines.append("## 6. End-to-End Traceability Matrix\n")
    if threats:
        matrix = TraceabilityMatrix()
        matrix.build(assets, threats, mitigations, requirements, risks)
        trace_rows = matrix.to_full_traceability_table()
        
        lines.append("| Target Asset | Attack Surface | Threat | Impact | Feasibility | Risk Score | Supporting Evidence | Mitigation Control | Review Status |")
        lines.append("|---|---|---|---|---|---|---|---|---|")
        for tr in trace_rows:
            lines.append(f"| {tr['Asset']} | {tr['Attack Surface']} | {tr['Threat']} | {tr['Impact']} | {tr['Feasibility']} | {tr['Risk Score']} | {tr['Supporting Evidence']} | {tr['Mitigation']} | {tr['Review Status']} |")
        lines.append("")
    else:
        lines.append("*Traceability matrix requires identified threats.*\n")
        
    # 7. Human Review Summary
    all_items = assets + surfaces + threats + risks + mitigations + requirements
    if all_items:
        lines.append("## 7. Human Review & Engineering Sign-Off Status\n")
        status_counts = {}
        for item in all_items:
            st_val = getattr(item, 'review_status', 'needs_review')
            status_counts[st_val] = status_counts.get(st_val, 0) + 1
        
        lines.append("| Review Status | Item Count | Description |")
        lines.append("|---|---|---|")
        lines.append(f"| Accepted | {status_counts.get('accepted', 0)} | Reviewed and accepted by cybersecurity engineer |")
        lines.append(f"| Needs Review | {status_counts.get('needs_review', 0)} | Candidate AI-generated item awaiting engineering review |")
        lines.append(f"| Edited | {status_counts.get('edited', 0)} | Modified during engineering review |")
        lines.append(f"| Rejected | {status_counts.get('rejected', 0)} | Rejected by cybersecurity engineer |")
        lines.append("")

    lines.append("---\n")
    lines.append("> **Advisory Disclaimer:** This report was generated with AI assistance as an engineering prototype informed by ISO/SAE 21434 and UNECE R155 principles. All candidate findings, qualitative impact levels, attack feasibility ratings, and defensive mitigations require formal review and approval by qualified automotive cybersecurity engineers before production implementation. No ISO/SAE 21434 certification or compliance is claimed.\n")

    return "\n".join(lines)
